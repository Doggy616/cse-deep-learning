import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
test('完成学习闭环、导出恢复、刷新持久化与断网学习', async ({page,context}) => {
  const errors: string[] = [];
  page.on('pageerror',e => errors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'学习首页'})).toBeVisible();
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  const manifest = await (await page.request.get('/manifest.webmanifest')).json();
  expect(manifest.display).toBe('standalone');
  expect(manifest.icons).toHaveLength(2);
  await page.evaluate(async () => { await navigator.serviceWorker.ready; });
  // A first visit may need a reload before the installed worker controls the page.
  await page.reload();
  await expect.poll(() => page.evaluate(() => Boolean(navigator.serviceWorker.controller))).toBe(true);
  await page.getByRole('button',{name:/安全生产管理/}).click();
  await page.getByRole('button',{name:'打开深度课程'}).first().click();
  await page.getByRole('button',{name:'标记已学完'}).click();
  await expect(page.getByRole('button',{name:'✓ 已学完此专题'})).toBeDisabled();
  await page.getByRole('button',{name:'进入关联综合题 →'}).click();
  await page.getByRole('checkbox',{name:/已登记台账/}).check();
  await page.getByRole('button',{name:'提交并查看解析'}).click();
  await expect(page.getByRole('heading',{name:'逐项解析'})).toBeVisible();
  await page.getByRole('navigation').getByRole('button',{name:/精准复习/}).click();
  await page.getByRole('button',{name:'立即复习'}).click();
  await page.getByRole('checkbox',{name:/先停用/}).check();
  await page.getByRole('checkbox',{name:/明确整改责任/}).check();
  await page.getByRole('button',{name:'提交并查看解析'}).click();
  await expect(page.getByRole('heading',{name:'✓ 演示作答正确'})).toBeVisible();
  await page.getByRole('navigation').getByRole('button',{name:'条件反转'}).click();
  await page.getByRole('button',{name:/修复了，能否立即销号/}).click();
  await expect(page.getByText('变化的条件')).toBeVisible();
  await page.getByRole('radio',{name:/组织复查/}).check();
  await page.getByRole('button',{name:'提交并查看解析'}).click();
  await expect(page.getByRole('heading',{name:'✓ 演示作答正确'})).toBeVisible();
  await page.getByRole('navigation').getByRole('button',{name:'数据与设置'}).click();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button',{name:'导出学习备份'}).click();
  const download = await downloadPromise;
  const backupPath = await download.path();
  const backup = JSON.parse(await readFile(backupPath!,'utf8'));
  expect(backup.data.attempts).toHaveLength(3);
  expect(backup.data.attempts.every((a: {grading:string}) => a.grading === 'demo')).toBe(true);
  await page.getByRole('button',{name:'清空数据…'}).click();
  await page.getByRole('button',{name:'确认清空所有学习记录'}).click();
  await expect(page.getByRole('status')).toContainText('已清空');
  await page.getByLabel('导入学习备份').setInputFiles({name:'备份.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(backup))});
  await expect(page.getByText('备份校验通过，尚未导入')).toBeVisible();
  await page.getByRole('button',{name:'确认替换并导入'}).click();
  await expect(page.getByRole('status')).toContainText('备份已导入');
  await page.reload();
  await page.getByRole('navigation').getByRole('button',{name:'精准复习'}).click();
  await expect(page.getByText('待巩固',{exact:true})).toBeVisible();
  await expect(page.getByText('查看后续复习安排')).toBeVisible();
  await context.setOffline(true);
  await page.reload();
  await expect(page.getByRole('heading',{name:'学习首页'})).toBeVisible();
  await expect(page.getByText('当前离线',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:/专题课程/}).click();
  await page.getByRole('button',{name:'打开深度课程'}).nth(1).click();
  await page.getByRole('button',{name:'标记已学完'}).click();
  await expect(page.getByRole('button',{name:'✓ 已学完此专题'})).toBeDisabled();
  await page.getByRole('button',{name:'进入关联综合题 →'}).click();
  await page.getByRole('checkbox',{name:/识别并隔离/}).check();
  await page.getByRole('checkbox',{name:/释放或约束/}).check();
  await page.getByRole('button',{name:'提交并查看解析'}).click();
  await expect(page.getByRole('heading',{name:'✓ 演示作答正确'})).toBeVisible();
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  expect(errors).toEqual([]);
  await context.setOffline(false);
});
